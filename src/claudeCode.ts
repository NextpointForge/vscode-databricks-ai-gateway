import * as os from 'node:os';
import * as path from 'node:path';
import * as vscode from 'vscode';
import { anthropicBaseUrl } from './config';
import { log } from './log';
import { CLAUDE_CODE_PIN_ENV_KEYS, GatewayModel, claudeCodeModelPins } from './models';
import { TokenService } from './tokenService';

/**
 * Claude Code reads its gateway credential by running `apiKeyHelper` and using
 * that command's stdout. It re-runs the helper every
 * CLAUDE_CODE_API_KEY_HELPER_TTL_MS, which is how a one-hour Databricks token
 * stays valid across a long session.
 */
const HELPER_TTL_MS = 900_000;

/** Only these keys are written. Everything else in the settings file is left alone. */
const MANAGED_ENV_KEYS = [
  'ANTHROPIC_BASE_URL',
  'CLAUDE_CODE_API_KEY_HELPER_TTL_MS',
  'CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS',
  ...CLAUDE_CODE_PIN_ENV_KEYS,
] as const;

export interface ClaudeCodeWiring {
  settingsPath: string;
  backupPath?: string;
  helperPath: string;
  baseUrl: string;
}

export class ClaudeCodeConfigurator {
  constructor(
    private readonly context: vscode.ExtensionContext,
    private readonly tokenService: TokenService,
  ) {}

  /**
   * Points Claude Code at the gateway: writes the helper script, merges the two
   * managed keys into the user Claude settings, and exports the base URL into new
   * integrated terminals.
   */
  async apply(workspaceOrigin: string, models: GatewayModel[]): Promise<ClaudeCodeWiring> {
    const endpoint = this.tokenService.endpoint;
    if (!endpoint) {
      throw new Error('The local token service is not running, so Claude Code cannot be configured.');
    }
    const baseUrl = anthropicBaseUrl(workspaceOrigin);
    const helperPath = await this.writeHelperScript(endpoint);
    const modelPins = claudeCodeModelPins(models);
    const { settingsPath, backupPath } = await this.mergeSettings(baseUrl, helperPath, modelPins);

    // Terminals launched from VS Code inherit the base URL, so `claude` in the
    // integrated terminal reaches the gateway without a wrapper script.
    const collection = this.context.environmentVariableCollection;
    collection.description = 'AI Gateway base URL for Claude Code';
    collection.replace('ANTHROPIC_BASE_URL', baseUrl);

    log.info(`Configured Claude Code for ${workspaceOrigin}.`);
    return { settingsPath, backupPath, helperPath, baseUrl };
  }

  /** Removes the managed keys and the terminal export, leaving other settings intact. */
  async revert(): Promise<void> {
    this.context.environmentVariableCollection.clear();
    await revertClaudeSettings(claudeSettingsPath());
  }

  /**
   * Writes the helper. It curls the loopback token service; the shared secret
   * lives in the script itself, which is created user-only (0600) inside the
   * extension's global storage. No Databricks token is ever written to disk.
   */
  private async writeHelperScript(endpoint: string): Promise<string> {
    const directory = this.context.globalStorageUri;
    await vscode.workspace.fs.createDirectory(directory);
    const secret = this.tokenService.sharedSecret;
    const target = vscode.Uri.joinPath(directory, helperBasename());

    const script =
      process.platform === 'win32'
        ? [
            '@echo off',
            'setlocal',
            `curl.exe -sf -H "Authorization: Bearer ${secret}" "${endpoint}"`,
            'exit /b %ERRORLEVEL%',
            '',
          ].join('\r\n')
        : [
            '#!/bin/sh',
            '# Generated by the AI Gateway Models VS Code extension.',
            '# Prints a short-lived Databricks OAuth token for Claude Code.',
            'set -eu',
            `exec curl -sf -H "Authorization: Bearer ${secret}" "${endpoint}"`,
            '',
          ].join('\n');

    await vscode.workspace.fs.writeFile(target, Buffer.from(script, 'utf8'));
    await restrictToOwner(target.fsPath);
    return target.fsPath;
  }

  private async mergeSettings(
    baseUrl: string,
    helperPath: string,
    modelPins: Record<string, string>,
  ): Promise<{ settingsPath: string; backupPath?: string }> {
    return await mergeClaudeSettings(claudeSettingsPath(), baseUrl, helperPath, modelPins);
  }
}

/**
 * Merges the managed keys into a Claude settings file.
 *
 * The file is read, backed up and rewritten with the rest of its contents
 * preserved: it is the user's own settings file and commonly holds unrelated
 * configuration. A file that is present but unparseable aborts the write rather
 * than being replaced.
 */
export async function mergeClaudeSettings(
  settingsPath: string,
  baseUrl: string,
  helperPath: string,
  modelPins: Record<string, string> = {},
): Promise<{ settingsPath: string; backupPath?: string }> {
  const existing = await readJsonFile(settingsPath);
  let backupPath: string | undefined;

  if (existing !== undefined) {
    backupPath = `${settingsPath}.ai-gateway.bak`;
    await vscode.workspace.fs.copy(vscode.Uri.file(settingsPath), vscode.Uri.file(backupPath), {
      overwrite: true,
    });
  }

  const settings: Record<string, unknown> = { ...(existing ?? {}) };
  const env: Record<string, unknown> = isRecord(settings['env']) ? { ...settings['env'] } : {};
  env['ANTHROPIC_BASE_URL'] = baseUrl;
  env['CLAUDE_CODE_API_KEY_HELPER_TTL_MS'] = String(HELPER_TTL_MS);
  // The gateway rejects unknown anthropic-beta values (e.g. advisor-tool-*, prompt-caching-scope-*) with a 400.
  env['CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS'] = '1';
  // Pins Claude Code's model aliases to what this gateway actually serves; see claudeCodeModelPins.
  for (const key of CLAUDE_CODE_PIN_ENV_KEYS) {
    delete env[key];
  }
  Object.assign(env, modelPins);
  settings['env'] = env;
  // Claude Code runs this value as a shell command, so a path containing spaces
  // (common under e.g. "Application Support" on macOS) must be quoted.
  settings['apiKeyHelper'] = quoteForShell(helperPath);

  await writeJsonFile(settingsPath, settings);
  return { settingsPath, backupPath };
}

/** Removes only this extension's keys, leaving the rest of the file as it was. */
export async function revertClaudeSettings(settingsPath: string): Promise<void> {
  const existing = await readJsonFile(settingsPath);
  if (!existing) {
    return;
  }
  const settings = { ...existing };
  if (isRecord(settings['env'])) {
    const env = { ...settings['env'] };
    for (const key of MANAGED_ENV_KEYS) {
      delete env[key];
    }
    if (Object.keys(env).length > 0) {
      settings['env'] = env;
    } else {
      delete settings['env'];
    }
  }
  // Only drop apiKeyHelper if it is the one we wrote; a hand-written helper stays.
  const helper = settings['apiKeyHelper'];
  if (typeof helper === 'string' && OWN_HELPER_BASENAMES.some((name) => helper.includes(name))) {
    delete settings['apiKeyHelper'];
  }
  await writeJsonFile(settingsPath, settings);
  log.info('Removed the managed keys from the Claude settings file.');
}

function helperBasename(): string {
  return process.platform === 'win32' ? 'ai-gateway-token.cmd' : 'ai-gateway-token.sh';
}

/** Helper names this extension has shipped, so a rename still cleans up after itself. */
const OWN_HELPER_BASENAMES = [
  'ai-gateway-token.cmd',
  'ai-gateway-token.sh',
  'databricks-aigw-token.cmd',
  'databricks-aigw-token.sh',
];

/** Quotes a path for use as a shell command, but only when it needs it, to keep plain paths readable. */
function quoteForShell(filePath: string): string {
  if (!/\s/.test(filePath)) {
    return filePath;
  }
  if (process.platform === 'win32') {
    return `"${filePath.replace(/"/g, '""')}"`;
  }
  return `'${filePath.replace(/'/g, `'\\''`)}'`;
}

export function claudeSettingsPath(): string {
  return path.join(os.homedir(), '.claude', 'settings.json');
}

async function readJsonFile(filePath: string): Promise<Record<string, unknown> | undefined> {
  let raw: Uint8Array;
  try {
    raw = await vscode.workspace.fs.readFile(vscode.Uri.file(filePath));
  } catch {
    return undefined;
  }
  const text = Buffer.from(raw).toString('utf8').trim();
  if (!text) {
    return {};
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    throw new Error(
      `${filePath} is not valid JSON, so it was left untouched. Fix or move it, then run ` +
        `"AI Gateway: Configure Claude Code" again. (${(error as Error).message})`,
    );
  }
  if (!isRecord(parsed)) {
    throw new Error(`${filePath} does not contain a JSON object, so it was left untouched.`);
  }
  return parsed;
}

async function writeJsonFile(filePath: string, value: Record<string, unknown>): Promise<void> {
  const directory = path.dirname(filePath);
  await vscode.workspace.fs.createDirectory(vscode.Uri.file(directory));
  const body = `${JSON.stringify(value, undefined, 2)}\n`;
  await vscode.workspace.fs.writeFile(vscode.Uri.file(filePath), Buffer.from(body, 'utf8'));
}

/** Best-effort 0600. POSIX only; on Windows the ACL inherited from the profile applies. */
async function restrictToOwner(filePath: string): Promise<void> {
  if (process.platform === 'win32') {
    return;
  }
  try {
    const { chmod } = await import('node:fs/promises');
    await chmod(filePath, 0o700);
  } catch (error) {
    log.warn(`Could not restrict permissions on ${filePath}: ${(error as Error).message}`);
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
